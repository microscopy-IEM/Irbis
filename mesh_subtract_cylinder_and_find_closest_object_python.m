function [nObjects, meshCell, basePoints] = mesh_subtract_cylinder_and_find_closest_object_python(mesh_data,vertices_original, varargin)

    tolerance = 1e-4;
    threshold = 0.1;
    min_sample_size = 50;
    green_threshold = 0.1;
    distance_threshold = 0.1;
    
    if nargin > 2
        library_selection = varargin{1};
    else
        library_selection = 1;
    end

    try
    if library_selection == 1
        output = pyrunfile('mesh_subtract_cylinder_and_find_closest_py_script.py',"output", ...
            mesh_data=mesh_data, ...
            vertices_original=vertices_original, ...
            tolerance=tolerance, ...
            threshold=threshold, ...
            min_sample_size=min_sample_size, ...
            green_threshold=green_threshold, ...
            distance_threshold=distance_threshold);
    elseif library_selection == 2
        output = pyrunfile('mesh_subtract_cylinder_and_find_closest_trimesh_py_script.py',"output", ...
            mesh_data=mesh_data, ...
            vertices_original=vertices_original, ...
            tolerance=tolerance, ...
            threshold=threshold, ...
            min_sample_size=min_sample_size, ...
            green_threshold=green_threshold, ...
            distance_threshold=distance_threshold);
    else
        error("Invalid library selection. Please choose 1 for pymeshlab or 2 for trimesh.");
    end

    catch ME
        disp(ME.message);
        error("Error in running the python script.");
    end


    % output = pyrunfile('mesh_subtract_cylinder_and_find_closest_py_script.py',"output", ...
    %     mesh_data=mesh_data, ...
    %     vertices_original=vertices_original, ...
    %     tolerance=tolerance, ...
    %     threshold=threshold, ...
    %     min_sample_size=min_sample_size, ...
    %     green_threshold=green_threshold, ...
    %     distance_threshold=distance_threshold);

    nObjects = int8(output{'n_objects'});

    componentData = output{'component_data'};

    meshCell = cell(1, nObjects);

    for i = 1:nObjects
        vertices = double(componentData{i}{'vertices'});
        faces = int32(componentData{i}{'faces'}) + 1;
        % vertexNormals = double(componentData{i}{'vertexNormals'});
        % faceNormals = double(componentData{i}{'faceNormals'});
        % meshCell{i} = surfaceMesh(vertices, faces, "VertexNormals", vertexNormals, "FaceNormals", faceNormals);
        meshCell{i} = surfaceMesh(vertices, faces);
    end

    basePoints = double(output{'base_points'});
end