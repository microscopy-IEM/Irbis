function generateDocPageReferenceDocs(sourceFile, outputFile, defaultTitle, defaultDescription)
% generateDocPageReferenceDocs Generate a Markdown page from %DOC_* blocks.

    if nargin < 3 || string(defaultTitle) == ""
        defaultTitle = "Reference";
    end

    if nargin < 4
        defaultDescription = "";
    end

    if isempty(sourceFile) || ~isfile(sourceFile)
        error("Source file not found: %s", sourceFile);
    end

    pageDocs = docgen.extractDocPageSections(sourceFile, defaultTitle, defaultDescription);
    lines = renderMarkdown(pageDocs, sourceFile);

    outputFolder = fileparts(outputFile);
    if ~isfolder(outputFolder)
        mkdir(outputFolder);
    end

    writeTextFile(outputFile, strjoin(lines, newline));

    fprintf("Generated documentation:\n%s\n", outputFile);
end

function lines = renderMarkdown(pageDocs, sourceFile)

    lines = strings(0, 1);

    lines(end+1) = "# " + pageDocs.title;
    lines(end+1) = "";

    if pageDocs.description ~= ""
        lines = appendParagraph(lines, pageDocs.description);
    end

    for i = 1:numel(pageDocs.sections)
        section = pageDocs.sections(i);

        lines(end+1) = "## " + section.title;
        lines(end+1) = "";

        if section.description ~= ""
            lines = appendParagraph(lines, section.description);
        end
    end

    lines(end+1) = "---";
    lines(end+1) = "";
    lines(end+1) = "*This page was generated automatically from: `" + string(sourceFile) + "`.*";
    lines(end+1) = "";
    lines(end+1) = "***Generated:** " + string(datetime("now", "Format", "yyyy-MM-dd HH:mm:ss")) + "*";
    lines(end+1) = "";
    lines(end+1) = "*Do not edit this file manually. Edit the documentation comments in the source file and regenerate the documentation.*";
end

function lines = appendParagraph(lines, textBlock)

    paragraphLines = splitlines(string(textBlock));

    for i = 1:numel(paragraphLines)
        lines(end+1) = paragraphLines(i); %#ok<AGROW>
    end

    lines(end+1) = "";
end

function writeTextFile(filePath, text)

    fid = fopen(filePath, "w");

    if fid == -1
        error("Could not open file for writing: %s", filePath);
    end

    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, "%s", text);
end
