function generateAdaptiveShaftGenerationParameterDocs(sourceFile, outputFile)
% generateAdaptiveShaftGenerationParameterDocs Generate adaptive shaft docs.

    if nargin < 1 || isempty(sourceFile)
        sourceFile = which("AdaptiveShaftGenerator");
    end

    if nargin < 2 || isempty(outputFile)
        outputFile = fullfile(pwd, "docs", "reference", "spine-generation-parameters", "adaptive-shaft-generation-parameters.md");
    end

    docgen.generateClassPropertyReferenceDocs( ...
        sourceFile, ...
        outputFile, ...
        "AdaptiveShaftGenerator", ...
        "Adaptive shaft generation parameters", ...
        "This page describes adaptive shaft reconstruction parameters used by `AdaptiveShaftGenerator`.", ...
        [], ...
        "Adaptive shaft settings", ...
        "These constructor-default properties were not found in the parsed properties block.");
end
