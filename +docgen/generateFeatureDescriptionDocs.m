function generateFeatureDescriptionDocs(sourceFile, outputFile)

    if nargin < 1 || isempty(sourceFile)
        sourceFile = which("ObjectFeatureExtractor");
    end

    if nargin < 2 || isempty(outputFile)
        outputFile = fullfile(pwd, "docs", "reference", "object-features.md");
    end

    features = docgen.extractFeatureDescriptions(sourceFile);

    lines = strings(0, 1);

    lines(end+1) = "# Object features";
    lines(end+1) = "";
    lines(end+1) = "This page describes mesh-derived object features calculated by `ObjectFeatureExtractor`.";
    lines(end+1) = "";

    for i = 1:numel(features)
        lines(end+1) = "## `" + escapeMarkdown(features(i).name) + "`";
        lines(end+1) = "";

        if features(i).meaning ~= ""
            lines(end+1) = "- **Meaning:** " + escapeMarkdown(features(i).meaning);
        end

        if features(i).formula ~= ""
            lines(end+1) = "- **Formula:** " + escapeMarkdown(features(i).formula);
        end

        if features(i).units ~= ""
            lines(end+1) = "- **Units:** " + escapeMarkdown(features(i).units);
        end

        lines(end+1) = "";
    end

    lines(end+1) = "---";
    lines(end+1) = "";
    lines(end+1) = "*This page was generated automatically from: `" + string(sourceFile) + "`.*";
    lines(end+1) = "";
    lines(end+1) = "***Generated:** " + string(datetime("now", "Format", "yyyy-MM-dd HH:mm:ss")) + "*";
    lines(end+1) = "";
    lines(end+1) = "*Do not edit this file manually. Edit the documentation comments in the source file and regenerate the documentation.*";

    outputFolder = fileparts(outputFile);
    if ~isfolder(outputFolder)
        mkdir(outputFolder);
    end

    writeTextFile(outputFile, strjoin(lines, newline));
end

function out = escapeMarkdown(in)
    out = string(in);
    out = replace(out, "|", "\|");
    out = replace(out, newline, " ");
end

function writeTextFile(filePath, text)

    fid = fopen(filePath, "w");

    if fid == -1
        error("Could not open file for writing: %s", filePath);
    end

    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, "%s", text);
end