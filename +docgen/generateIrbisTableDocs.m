function specialTypesArg = prepareSpecialTypesArg(specialTypes)

    if isempty(specialTypes)
        specialTypesArg = {''};
    else
        specialTypesArg = specialTypes;
    end
end

function lines = appendTableMetadata(lines, T)

    varNames = string(T.Properties.VariableNames);
    varTypes = string(varfun(@class, T, "OutputFormat", "cell"));

    units = strings(size(varNames));
    descriptions = strings(size(varNames));

    if ~isempty(T.Properties.VariableUnits)
        units = string(T.Properties.VariableUnits);
    end

    if ~isempty(T.Properties.VariableDescriptions)
        descriptions = string(T.Properties.VariableDescriptions);
    end

    lines(end+1) = "| Variable | Type | Unit | Description |";
    lines(end+1) = "|---|---|---|---|";

    for i = 1:numel(varNames)
        lines(end+1) = "| " + escapeMarkdown(varNames(i)) + ...
            " | " + escapeMarkdown(varTypes(i)) + ...
            " | " + escapeMarkdown(units(i)) + ...
            " | " + escapeMarkdown(descriptions(i)) + " |";
    end
end

function out = escapeMarkdown(in)
    out = string(in);
    out = replace(out, "|", "\|");
    out = replace(out, newline, " ");
end

function T = removeDefaultVariables(T, defaultVarNames)

    varNames = string(T.Properties.VariableNames);
    keepMask = ~ismember(varNames, defaultVarNames);

    T = T(:, keepMask);
end

function writeTextFile(filePath, text)

    fid = fopen(filePath, "w");

    if fid == -1
        error("Could not open file for writing: %s", filePath);
    end

    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, "%s", text);
end