function generateIrbisTableDocs(outputFolder)
% generateIrbisTableDocs Generate MkDocs Markdown reference pages
% from Irbis table metadata defined in getBaseStruct.m.

    if nargin < 1
        outputFolder = fullfile(pwd, "docs", "reference");
    end

    if ~isfolder(outputFolder)
        mkdir(outputFolder);
    end

    pageSpecs = {
        "model",  "model-table.md",  "Model table", {
            {},                   "Basic model table";
            {'derived'},          "Shaft parameters";
            {'spines'},           "Spine parameters";
        };

        "tracks", "tracks-table.md", "Tracks table", {
            {}, "Tracks list table";
        };

        "points", "points-table.md", "Points table", {
            {}, "Points list table";
        };

        "views", "views-table.md", "Stored views table", {
            {}, "Stored views table";
        };

        "tools", "areas-table.md", "Areas table", {
            {'areas'}, "Areas table";
        };
    };

    for i = 1:size(pageSpecs, 1)
        structType = pageSpecs{i, 1};
        fileName = pageSpecs{i, 2};
        pageTitle = pageSpecs{i, 3};
        tableGroups = pageSpecs{i, 4};

        md = groupedTableMetadataToMarkdown(structType, pageTitle, tableGroups);

        outputPath = fullfile(outputFolder, fileName);
        writeTextFile(outputPath, md);
    end

    fprintf("Documentation generated in:\n%s\n", outputFolder);
end

function md = groupedTableMetadataToMarkdown(structType, pageTitle, tableGroups)

    lines = strings(0, 1);

    lines(end+1) = "# " + pageTitle;
    lines(end+1) = "";

    defaultT = getBaseStruct("table", char(structType), 0, {''});
    defaultVarNames = string(defaultT.Properties.VariableNames);

    for i = 1:size(tableGroups, 1)
        specialTypes = tableGroups{i, 1};
        sectionTitle = tableGroups{i, 2};

        specialTypesArg = prepareSpecialTypesArg(specialTypes);

        T = getBaseStruct("table", char(structType), 0, specialTypesArg);

        if ~isempty(specialTypes)
            T = removeDefaultVariables(T, defaultVarNames);
        end

        lines(end+1) = "## " + sectionTitle;
        lines(end+1) = "";

        if width(T) == 0
            lines(end+1) = "No additional parameters beyond the default table.";
            lines(end+1) = "";
        else
            lines = appendTableMetadata(lines, T);
            lines(end+1) = "";
        end
    end

    lines(end+1) = "---";
    lines(end+1) = "";
    lines(end+1) = "*This page was generated automatically from: `getBaseStruct.m`.*";
    lines(end+1) = "";
    lines(end+1) = "***Generated:** " + string(datetime("now", "Format", "yyyy-MM-dd HH:mm:ss")) + "*";
    lines(end+1) = "";
    lines(end+1) = "*Do not edit this file manually. Edit the documentation comments in the source file and regenerate the documentation.*";


    md = strjoin(lines, newline);
end

