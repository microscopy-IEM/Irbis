    function updateLayout(~, ~)
        meshVisible = logical(get(meshExportCheckbox, 'Value'));
        maskVisible = logical(get(maskExportCheckbox, 'Value'));

        set(meshPanel, 'Visible', onOff(meshVisible));
        set(maskPanel, 'Visible', onOff(maskVisible));

        figHeight = ...
            margin + ...
            (2 * rowHeight) + rowGap + ...
            sectionGap + headerHeight + ...
            double(meshVisible) * (rowGap + meshPanelHeight) + ...
            sectionGap + headerHeight + ...
            double(maskVisible) * (rowGap + maskPanelHeight) + ...
            sectionGap + headerHeight + tableHeight + ...
            bottomAreaHeight;

        oldPosition = get(fig, 'Position');
        newY = oldPosition(2) + oldPosition(4) - figHeight;
        set(fig, 'Position', [oldPosition(1) newY figWidth figHeight]);

        y = figHeight - margin - rowHeight;

        set(outputPathLabel, 'Position', [margin y 100 22]);
        set(outputFolderEdit, 'Position', [125 y 520 26]);
        set(browseButton, 'Position', [655 y 85 26]);

        y = y - rowHeight - rowGap;
        set(outputFolderNameLabel, 'Position', [margin y 100 22]);
        set(outputFolderNameEdit, 'Position', [125 y 300 26]);
        set(dumpDirectlyCheckbox, 'Position', [435 y 305 24]);

        y = y - sectionGap - headerHeight;
        set(meshExportCheckbox, 'Position', [margin y 260 24]);

        if meshVisible
            y = y - rowGap - meshPanelHeight;
            set(meshPanel, 'Position', [margin y figWidth - 2 * margin meshPanelHeight]);
        end

        y = y - sectionGap - headerHeight;
        set(maskExportCheckbox, 'Position', [margin y 300 24]);

        if maskVisible
            y = y - rowGap - maskPanelHeight;
            set(maskPanel, 'Position', [margin y figWidth - 2 * margin maskPanelHeight]);
        end

        y = y - sectionGap - headerHeight;
        tableTopY = y;
        tableY = tableTopY - tableHeight;

        set(branchLabel, 'Position', [margin tableTopY 100 22]);
        set(branchSelectAllButton, 'Position', [220 tableTopY 60 22]);
        set(branchUnselectAllButton, 'Position', [285 tableTopY 65 22]);
        set(branchTable, 'Position', [margin tableY 350 tableHeight]);

        set(timePointLabel, 'Position', [390 tableTopY 100 22]);
        set(timePointSelectAllButton, 'Position', [590 tableTopY 60 22]);
        set(timePointUnselectAllButton, 'Position', [655 tableTopY 65 22]);
        set(timePointTable, 'Position', [390 tableY 350 tableHeight]);

        set(confirmButton, 'Position', [510 margin 100 bottomButtonHeight]);
        set(cancelButton, 'Position', [630 margin 100 bottomButtonHeight]);
    end

    function onSectionToggle(~, ~)
        updateLayout();
    end

    function onMaskDestinationChanged(~, ~)
        storesChannel = maskDestinationStoresChannel(getMaskDestination());

        set(newChannelNameLabel, 'Enable', onOff(storesChannel));
        set(newChannelNameEdit, 'Enable', onOff(storesChannel));
    end

    function onMaskModeChanged(~, ~)
        rawDataSelected = isRawDataMode();

        set(maskChannelLabel, 'Enable', onOff(rawDataSelected));
        set(maskChannelDropdown, 'Enable', onOff(rawDataSelected));
        set(setBackgroundCheckbox, 'Enable', onOff(rawDataSelected));
        set(setForegroundCheckbox, 'Enable', onOff(rawDataSelected));

        onFixedValueToggle();
    end

    function onFixedValueToggle(~, ~)
        rawDataSelected = isRawDataMode();

        set(backgroundValueEdit, 'Enable', onOff( ...
            rawDataSelected && logical(get(setBackgroundCheckbox, 'Value'))));
        set(foregroundValueEdit, 'Enable', onOff( ...
            rawDataSelected && logical(get(setForegroundCheckbox, 'Value'))));
    end

    function rawDataSelected = isRawDataMode()
        selectedLabelModeIndex = get(maskLabelModeDropdown, 'Value');
        rawDataSelected = strcmp(labelModeValues{selectedLabelModeIndex}, 'rawData');
    end

    function maskDestination = getMaskDestination()
        selectedDestinationObject = get(maskDestinationGroup, 'SelectedObject');
        if isempty(selectedDestinationObject)
            maskDestination = maskDestinationDefault;
        else
            maskDestination = get(selectedDestinationObject, 'Tag');
        end
    end

    function includesFiles = maskDestinationIncludesFiles(maskDestination)
        includesFiles = strcmp(maskDestination, 'exportFiles') || strcmp(maskDestination, 'exportAndStore');
    end

    function storesChannel = maskDestinationStoresChannel(maskDestination)
        storesChannel = strcmp(maskDestination, 'storeChannel') || strcmp(maskDestination, 'exportAndStore');
    end

    function onBrowse(~, ~)
        currentPath = get(outputFolderEdit, 'String');
        if ~isfolder(currentPath)
            currentPath = pwd;
        end

        selectedPath = uigetdir(currentPath, 'Select output folder');
        if ~isequal(selectedPath, 0)
            set(outputFolderEdit, 'String', char(selectedPath));
        end
    end

    function branchSelectAll(~, ~)
        branchData(:, 1) = {true};
        branchTable.Data = branchData;
    end

    function branchUnselectAll(~, ~)
        branchData(:, 1) = {false};
        branchTable.Data = branchData;
    end

    function timePointSelectAll(~, ~)
        timePointData(:, 1) = {true};
        timePointTable.Data = timePointData;
    end

    function timePointUnselectAll(~, ~)
        timePointData(:, 1) = {false};
        timePointTable.Data = timePointData;
    end

    function onConfirm(~, ~)
        meshEnabled = logical(get(meshExportCheckbox, 'Value'));
        maskEnabled = logical(get(maskExportCheckbox, 'Value'));

        if ~meshEnabled && ~maskEnabled
            errordlg('Select at least one export type: mesh export or voxelized object masks.', 'Export settings');
            return;
        end

        selectedMaskDestination = getMaskDestination();
        maskExportsFiles = maskEnabled && maskDestinationIncludesFiles(selectedMaskDestination);
        maskStoresChannel = maskEnabled && maskDestinationStoresChannel(selectedMaskDestination);
        outputPathRequired = meshEnabled || maskExportsFiles;

        selectedOutputBaseFolder = strtrim(get(outputFolderEdit, 'String'));
        if outputPathRequired && isempty(selectedOutputBaseFolder)
            errordlg('Select an output path.', 'Export settings');
            return;
        end

        selectedNewChannelName = strtrim(get(newChannelNameEdit, 'String'));
        if maskStoresChannel && isempty(selectedNewChannelName)
            errordlg('Enter a name for the new mask channel.', 'Export settings');
            return;
        end

        branchMask = cell2mat(branchTable.Data(:, 1));
        timePointMask = cell2mat(timePointTable.Data(:, 1));

        selectedBranchIndices = find(branchMask);
        selectedTimePointIndices = find(timePointMask);

        if isempty(selectedBranchIndices)
            errordlg('Select at least one branch.', 'Export settings');
            return;
        end

        if isempty(selectedTimePointIndices)
            errordlg('Select at least one time point.', 'Export settings');
            return;
        end

        selectedLabelModeIndex = get(maskLabelModeDropdown, 'Value');
        selectedLabelMode = labelModeValues{selectedLabelModeIndex};
        rawDataSelected = strcmp(selectedLabelMode, 'rawData');
        rawDataExportSelected = maskEnabled && rawDataSelected;

        if rawDataExportSelected
            [backgroundValue, backgroundValueIsValid] = readOptionalNumericValue( ...
                setBackgroundCheckbox, backgroundValueEdit);
            if ~backgroundValueIsValid
                errordlg('Background fixed value must be numeric.', 'Export settings');
                return;
            end

            [foregroundValue, foregroundValueIsValid] = readOptionalNumericValue( ...
                setForegroundCheckbox, foregroundValueEdit);
            if ~foregroundValueIsValid
                errordlg('Foreground fixed value must be numeric.', 'Export settings');
                return;
            end
        else
            backgroundValue = [];
            foregroundValue = [];
        end

        selectedOutputFolderName = strtrim(get(outputFolderNameEdit, 'String'));
        dumpDirectlyToSelectedOutputFolder = logical(get(dumpDirectlyCheckbox, 'Value'));

        if ~outputPathRequired || isempty(selectedOutputBaseFolder)
            outputFolder = '';
        elseif dumpDirectlyToSelectedOutputFolder || isempty(selectedOutputFolderName)
            outputFolder = selectedOutputBaseFolder;
        else
            outputFolder = fullfile(selectedOutputBaseFolder, selectedOutputFolderName);
        end

        selectedFormat = outputFormats{get(outputFormatDropdown, 'Value')};
        selectedChannelDropdownIndex = get(maskChannelDropdown, 'Value');
        selectedChannelIndex = channelIndices(selectedChannelDropdownIndex);
        selectedChannelName = channelDisplay{selectedChannelDropdownIndex};
        selectedExtentObject = get(maskExtentGroup, 'SelectedObject');
        selectedMaskExtent = get(selectedExtentObject, 'Tag');

        settings = defaultSettings();
        settings.outputFolder = outputFolder;
        settings.outputBaseFolder = selectedOutputBaseFolder;
        settings.outputFolderName = selectedOutputFolderName;
        settings.dumpDirectlyToSelectedOutputFolder = dumpDirectlyToSelectedOutputFolder;
        settings.selectedBranches = branchNames(selectedBranchIndices);
        settings.selectedTimePoints = reshape(numericTimePoints(selectedTimePointIndices), 1, []);

        settings.mesh.enabled = meshEnabled;
        settings.mesh.format = selectedFormat;
        settings.mesh.centerMeshes = logical(get(centerMeshCheckbox, 'Value'));

        settings.mask.enabled = maskEnabled;
        settings.mask.destination = selectedMaskDestination;
        settings.mask.exportFiles = maskExportsFiles;
        settings.mask.storeAsChannel = maskStoresChannel;
        settings.mask.newChannelName = selectedNewChannelName;
        settings.mask.labelMode = selectedLabelMode;
        settings.mask.labelModeLabel = labelModeLabels{selectedLabelModeIndex};
        settings.mask.extent = selectedMaskExtent;
        settings.mask.exportFullVolume = strcmp(selectedMaskExtent, 'fullVolume');
        settings.mask.exportCroppedPerObject = strcmp(selectedMaskExtent, 'croppedPerObject');
        settings.mask.background.useFixedValue = rawDataExportSelected && logical(get(setBackgroundCheckbox, 'Value'));
        settings.mask.background.value = backgroundValue;
        settings.mask.foreground.useFixedValue = rawDataExportSelected && logical(get(setForegroundCheckbox, 'Value'));
        settings.mask.foreground.value = foregroundValue;
        settings.mask.foreground.overridesLabels = false;
        settings.mask.rawData.enabled = rawDataExportSelected;
        settings.mask.rawData.channelIndex = selectedChannelIndex;
        settings.mask.rawData.channelName = selectedChannelName;
        settings.mask.selectedChannelIndex = selectedChannelIndex;
        settings.mask.selectedChannelName = selectedChannelName;

        % Top-level aliases keep the original mesh dialog settings easy to find.
        settings.selectedFormat = settings.mesh.format;
        settings.centerMeshes = settings.mesh.centerMeshes;

        isCancelled = false;
        closeDialog();
    end

