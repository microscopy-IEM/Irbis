        set(outputFormatDropdown, 'Position', [120 36 125 26]);
        set(centerMeshCheckbox, 'Position', [425 36 305 24]);

        set(maskOutputLabel, 'Position', [15 198 100 22]);
        set(maskDestinationGroup, 'Position', [120 158 285 66]);
        set(exportFilesRadio, 'Position', [0 42 180 22]);
        set(storeChannelRadio, 'Position', [0 21 180 22]);
        set(exportAndStoreRadio, 'Position', [0 0 285 22]);
        set(newChannelNameLabel, 'Position', [425 198 120 22]);
        set(newChannelNameEdit, 'Position', [545 198 185 26]);
        set(maskLabelModeLabel, 'Position', [15 124 100 22]);
        set(maskLabelModeDropdown, 'Position', [120 124 245 26]);
        set(maskChannelLabel, 'Position', [425 124 100 22]);
        set(maskChannelDropdown, 'Position', [535 124 195 26]);
        set(maskExtentLabel, 'Position', [15 82 100 22]);
        set(maskExtentGroup, 'Position', [120 76 300 48]);
        set(fullVolumeRadio, 'Position', [0 24 285 22]);
        set(croppedObjectRadio, 'Position', [0 0 285 22]);
        set(setBackgroundCheckbox, 'Position', [425 84 235 24]);
        set(backgroundValueEdit, 'Position', [665 84 65 26]);
        set(setForegroundCheckbox, 'Position', [425 44 235 24]);
