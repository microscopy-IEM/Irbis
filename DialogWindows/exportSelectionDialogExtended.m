function [settings, isCancelled] = exportSelectionDialogExtended(branchNames, timePoints, initialOutputFolder, datasetName, channelNames)
% exportSelectionDialogExtended opens a modal dialog for mesh and mask export settings.
%
% This dialog extends exportSelectionDialog by keeping the shared export
% destination/selection controls and adding independently enabled mesh and
% voxelized mask export sections.
%
% Inputs:
%   branchNames         - cell array/string array of branch names
%   timePoints          - numeric, cell array, or string array of time points
%   initialOutputFolder - (optional) initial folder path shown in the edit box
%   datasetName         - (optional) default value for output folder name
%   channelNames        - (optional) cell/string array of raw image channels
%
% Outputs:
%   settings    - struct with shared, mesh, and mask export settings
%   isCancelled - true if user cancelled/closed the dialog, false on Confirm

    if nargin < 3 || isempty(initialOutputFolder)
        initialOutputFolder = pwd;
    end

    if nargin < 4 || isempty(datasetName)
        datasetName = '';
    end

    if nargin < 5 || isempty(channelNames)
        channelNames = {'ch1'};
    end

    % Normalize the branch names into a cell array of character vectors.
    if isstring(branchNames)
        branchNames = cellstr(branchNames(:));
    elseif ischar(branchNames)
        branchNames = {branchNames};
    else
        branchNames = branchNames(:);
    end

    % Normalize time points for display and keep a numeric copy for output.
    if isnumeric(timePoints)
        numericTimePoints = double(timePoints(:));
        timePointDisplay = cellstr(string(numericTimePoints));
    elseif isstring(timePoints)
        timePoints = timePoints(:);
        numericTimePoints = str2double(timePoints);
        if any(isnan(numericTimePoints))
            error('timePoints must contain numeric values only.');
        end
        timePointDisplay = cellstr(timePoints);
    elseif ischar(timePoints)
        numericTimePoints = str2double(string(timePoints));
        if isnan(numericTimePoints)
            error('timePoints must contain numeric values only.');
        end
        numericTimePoints = numericTimePoints(:);
        timePointDisplay = {timePoints};
    else
        timePoints = timePoints(:);
        timePointDisplay = cell(size(timePoints));
        for i = 1:numel(timePoints)
            timePointDisplay{i} = string(timePoints{i});
        end
        numericTimePoints = str2double(string(timePointDisplay));
        if any(isnan(numericTimePoints))
            error('timePoints must contain numeric values only.');
        end
        timePointDisplay = cellstr(string(timePointDisplay));
    end

    if isempty(branchNames)
        error('branchNames must contain at least one item.');
    end

    if isempty(timePointDisplay)
        error('timePoints must contain at least one item.');
    end

    % Normalize channel names for the raw-data mask mode.
    if isnumeric(channelNames)
        channelIndices = double(channelNames(:));
        channelDisplay = cellstr("ch" + string(channelIndices));
    elseif isstring(channelNames)
        channelDisplay = cellstr(channelNames(:));
        channelIndices = (1:numel(channelDisplay)).';
    elseif ischar(channelNames)
        channelDisplay = {channelNames};
        channelIndices = 1;
    else
        channelNames = channelNames(:);
        channelDisplay = cell(size(channelNames));
        for i = 1:numel(channelNames)
            channelDisplay{i} = char(string(channelNames{i}));
        end
        channelIndices = (1:numel(channelDisplay)).';
    end

    if isempty(channelDisplay)
        channelDisplay = {'ch1'};
        channelIndices = 1;
    end

    maskDestinationDefault = 'exportFiles';
    defaultNewChannelName = 'objectId_mask';

    % Default outputs are used when the user cancels or closes the window.
    settings = defaultSettings();
    isCancelled = true;

    % Supported surface mesh file formats from writeSurfaceMesh.
    % 3mf format is special and goes through a dedicated function.
    outputFormats = {'stl', 'ply', 'fbx', 'obj', 'gltf', 'glb', 'off', 'dae', '3mf'};
    outputFormatsDocUrl = 'https://www.mathworks.com/help/lidar/ref/writesurfacemesh.html#mw_ca2fbf17-69fb-41ca-b2de-2bb249aeb950';

    labelModeLabels = { ...
        'Label image based on objectId', ...
        'Label image based on groupId', ...
        'Binary image', ...
        'Mask raw data' ...
    };
    labelModeValues = {'objectId', 'groupId', 'binary', 'rawData'};

    figWidth = 800;
    margin = 20;
    rowHeight = 26;
    rowGap = 8;
    sectionGap = 10;
    headerHeight = 24;
    meshPanelHeight = 72;
    maskPanelHeight = 238;
    tableHeight = 250;
    bottomButtonHeight = 38;
    bottomAreaHeight = 73;

    fig = figure( ...
        'Name', 'Export Settings', ...
        'NumberTitle', 'off', ...
        'MenuBar', 'none', ...
        'ToolBar', 'none', ...
        'Resize', 'off', ...
        'WindowStyle', 'modal', ...
        'Position', [300 120 figWidth 720], ...
        'CloseRequestFcn', @onCancel ...
    );

    outputPathLabel = uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Output path:', ...
        'HorizontalAlignment', 'left' ...
    );

    outputFolderEdit = uicontrol( ...
        'Parent', fig, ...
        'Style', 'edit', ...
        'String', initialOutputFolder, ...
        'HorizontalAlignment', 'left' ...
    );

    browseButton = uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Browse...', ...
        'Callback', @onBrowse ...
    );

    outputFolderNameLabel = uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Output folder name:', ...
        'HorizontalAlignment', 'left' ...
    );

    outputFolderNameEdit = uicontrol( ...
        'Parent', fig, ...
        'Style', 'edit', ...
        'String', char(datasetName), ...
        'HorizontalAlignment', 'left' ...
    );

    dumpDirectlyCheckbox = uicontrol( ...
        'Parent', fig, ...
        'Style', 'checkbox', ...
        'String', 'Do not create subfolder', ...
        'Value', 0, ...
        'TooltipString', 'If enabled, files are exported directly to the selected output folder without creating an output subfolder.' ...
