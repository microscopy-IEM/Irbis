    );

    branchLabel = uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Branches:', ...
        'HorizontalAlignment', 'left' ...
    );

    branchSelectAllButton = uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Select All', ...
        'Callback', @branchSelectAll ...
    );

    branchUnselectAllButton = uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Unselect All', ...
        'Callback', @branchUnselectAll ...
    );

    branchData = [num2cell(true(numel(branchNames), 1)), branchNames(:)];
    branchTable = uitable( ...
        'Parent', fig, ...
        'Data', branchData, ...
        'ColumnName', {'Export', 'Branch'}, ...
        'ColumnFormat', {'logical', 'char'}, ...
        'ColumnEditable', [true false], ...
        'ColumnWidth', {60 285}, ...
        'RowName', [] ...
    );

    timePointLabel = uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Time points:', ...
        'HorizontalAlignment', 'left' ...
    );

    timePointSelectAllButton = uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Select All', ...
        'Callback', @timePointSelectAll ...
    );

    timePointUnselectAllButton = uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Unselect All', ...
        'Callback', @timePointUnselectAll ...
    );

    timePointData = [num2cell(true(numel(timePointDisplay), 1)), timePointDisplay(:)];
    timePointTable = uitable( ...
        'Parent', fig, ...
        'Data', timePointData, ...
        'ColumnName', {'Export', 'Time point'}, ...
        'ColumnFormat', {'logical', 'char'}, ...
        'ColumnEditable', [true false], ...
        'ColumnWidth', {60 285}, ...
        'RowName', [] ...
    );

    confirmButton = uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Confirm', ...
        'Callback', @onConfirm ...
    );

    cancelButton = uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Cancel', ...
        'Callback', @onCancel ...
    );

    positionStaticPanelContents();
    updateLayout();
    onMaskModeChanged();
    onMaskDestinationChanged();
    uiwait(fig);

