    function [value, isValid] = readOptionalNumericValue(checkboxHandle, editHandle)
        if ~logical(get(checkboxHandle, 'Value'))
            value = [];
            isValid = true;
            return;
        end

        value = str2double(strtrim(get(editHandle, 'String')));
        isValid = ~isnan(value);
    end

