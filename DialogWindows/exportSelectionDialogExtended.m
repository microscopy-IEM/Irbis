        'HorizontalAlignment', 'left', ...
        'Enable', 'off' ...
    );

    maskLabelModeLabel = uicontrol( ...
        'Parent', maskPanel, ...
        'Style', 'text', ...
        'String', 'Mask values:', ...
        'HorizontalAlignment', 'left' ...
    );

    maskLabelModeDropdown = uicontrol( ...
        'Parent', maskPanel, ...
        'Style', 'popupmenu', ...
        'String', labelModeLabels, ...
        'Value', 1, ...
        'Callback', @onMaskModeChanged ...
    );

    maskChannelLabel = uicontrol( ...
        'Parent', maskPanel, ...
        'Style', 'text', ...
        'String', 'Raw channel:', ...
        'HorizontalAlignment', 'left', ...
        'Enable', 'off' ...
    );

    maskChannelDropdown = uicontrol( ...
        'Parent', maskPanel, ...
        'Style', 'popupmenu', ...
        'String', channelDisplay, ...
        'Value', 1, ...
        'Enable', 'off' ...
    );

    maskExtentLabel = uicontrol( ...
        'Parent', maskPanel, ...
        'Style', 'text', ...
        'String', 'Mask extent:', ...
        'HorizontalAlignment', 'left' ...
