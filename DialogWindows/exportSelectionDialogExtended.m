        'BorderType', 'line', ...
        'Visible', 'off' ...
    );

    maskOutputLabel = uicontrol( ...
        'Parent', maskPanel, ...
        'Style', 'text', ...
        'String', 'Mask output:', ...
        'HorizontalAlignment', 'left' ...
    );

    maskDestinationGroup = uibuttongroup( ...
        'Parent', maskPanel, ...
        'Units', 'pixels', ...
