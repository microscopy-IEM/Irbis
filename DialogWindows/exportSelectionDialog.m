function [outputFolder, selectedFormat, centerMeshes, selectedBranches, selectedTimePoints, isCancelled] = exportSelectionDialog(branchNames, timePoints, initialOutputFolder, datasetName)
% exportSelectionDialog opens a modal dialog for export settings.
% The output is used to configure the export of surface meshes using writeSurfaceMesh
%
% Inputs:
%   branchNames        - cell array/string array of branch names
%   timePoints         - numeric, cell array, or string array of time points
%   initialOutputFolder - (optional) initial folder path shown in the edit box
%   datasetName        - (optional) default value for output folder name
%
% Outputs:
%   outputFolder      - selected export folder path
%   selectedFormat    - selected output file format
%   centerMeshes      - true if each mesh should be centered before export
%   selectedBranches  - selected branch names
%   selectedTimePoints - selected time points as a numeric array
%   isCancelled       - true if user cancelled/closed the dialog, false on Confirm

    if nargin < 3 || isempty(initialOutputFolder)
        initialOutputFolder = pwd;
    end

    if nargin < 4 || isempty(datasetName)
        datasetName = '';
    end

    % Normalize the branch names into a cell array of character vectors.
    if isstring(branchNames)
        branchNames = cellstr(branchNames(:));
    elseif ischar(branchNames)
        branchNames = {branchNames};
    else
        branchNames = branchNames(:);
    end

    % Normalize time points for display and keep a numeric copy for the output.
    if isnumeric(timePoints)
        numericTimePoints = double(timePoints(:));
        timePointDisplay = cellstr(string(numericTimePoints));
    elseif isstring(timePoints)
        timePoints = timePoints(:);
        numericTimePoints = str2double(timePoints);
        if any(isnan(numericTimePoints))
            error('timePoints must contain numeric values only.');
        end
        timePointDisplay = cellstr(timePoints);
    elseif ischar(timePoints)
        numericTimePoints = str2double(string(timePoints));
        if isnan(numericTimePoints)
            error('timePoints must contain numeric values only.');
        end
        numericTimePoints = numericTimePoints(:);
        timePointDisplay = {timePoints};
    else
        timePoints = timePoints(:);
        timePointDisplay = cell(size(timePoints));
        for i = 1:numel(timePoints)
            timePointDisplay{i} = string(timePoints{i});
        end
        numericTimePoints = str2double(string(timePointDisplay));
        if any(isnan(numericTimePoints))
            error('timePoints must contain numeric values only.');
        end
        timePointDisplay = cellstr(string(timePointDisplay));
    end

    if isempty(branchNames)
        error('branchNames must contain at least one item.');
    end

    if isempty(timePointDisplay)
        error('timePoints must contain at least one item.');
    end

    % Default outputs are used when the user cancels or closes the window.
    outputFolder = '';
    selectedFormat = 'stl';
    centerMeshes = false;
    selectedBranches = {};
    selectedTimePoints = [];
    isCancelled = true;

    % Supported surface mesh file formats from writeSurfaceMesh.
    outputFormats = {'stl', 'ply', 'fbx', 'obj', 'gltf', 'glb', 'off', 'dae'};
    outputFormatsDocUrl = 'https://www.mathworks.com/help/lidar/ref/writesurfacemesh.html#mw_ca2fbf17-69fb-41ca-b2de-2bb249aeb950';

    % Create a modal dialog so the caller waits for a decision.
    fig = figure( ...
        'Name', 'Export Settings', ...
        'NumberTitle', 'off', ...
        'MenuBar', 'none', ...
        'ToolBar', 'none', ...
        'Resize', 'off', ...
        'WindowStyle', 'modal', ...
        'Position', [300 200 760 520], ...
        'CloseRequestFcn', @onCancel ...
    );

    % Output folder row: label, edit field, and browse button.
    uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Output path:', ...
        'HorizontalAlignment', 'left', ...
        'Position', [20 480 100 22] ...
    );

    outputFolderEdit = uicontrol( ...
        'Parent', fig, ...
        'Style', 'edit', ...
        'String', initialOutputFolder, ...
        'HorizontalAlignment', 'left', ...
        'Position', [125 480 520 26] ...
    );

    uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Browse...', ...
        'Position', [655 480 85 26], ...
        'Callback', @onBrowse ...
    );

    % Output folder-name row and optional direct export toggle.
    uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Output folder name:', ...
        'HorizontalAlignment', 'left', ...
        'Position', [20 448 100 22] ...
    );

    outputFolderNameEdit = uicontrol( ...
        'Parent', fig, ...
        'Style', 'edit', ...
        'String', char(datasetName), ...
        'HorizontalAlignment', 'left', ...
        'Position', [125 448 300 26] ...
    );

    dumpDirectlyCheckbox = uicontrol( ...
        'Parent', fig, ...
        'Style', 'checkbox', ...
        'String', 'Do not create subfolder', ...
        'Value', 0, ...
        'TooltipString', 'If enabled, files are exported directly to the selected output folder without creating an output subfolder.', ...
        'Position', [435 447 305 24] ...
    );

    % Output format row: dropdown plus documentation link.
    uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Output format:', ...
        'HorizontalAlignment', 'left', ...
        'Position', [20 415 100 22] ...
    );

    outputFormatDropdown = uicontrol( ...
        'Parent', fig, ...
        'Style', 'popupmenu', ...
        'String', outputFormats, ...
        'Value', 1, ...
        'Position', [125 415 140 26] ...
    );

    % Hyperlink to the MATLAB documentation for the supported formats.
    uihyperlink( ...
        'Parent', fig, ...
        'Text', '?', ...
        'URL', outputFormatsDocUrl, ...
        'HorizontalAlignment', 'left', ...
        'Position', [270 415 90 22] ...
    );

    % Optional centering step for each mesh before export.
    centerMeshCheckbox = uicontrol( ...
        'Parent', fig, ...
        'Style', 'checkbox', ...
        'String', 'Center mesh', ...
        'Value', 0, ...
        'TooltipString', 'If enabled, each mesh will be translated so its centroid is at the origin before export.', ...
        'Position', [435 415 305 24] ...
    );

    % Branch checklist, preselected by default.
    uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Branches:', ...
        'HorizontalAlignment', 'left', ...
        'Position', [20 385 100 22] ...
    );

    uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Select All', ...
        'Position', [220 385 60 22], ...
        'Callback', @branchSelectAll ...
    );

    uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Unselect All', ...
        'Position', [285 385 65 22], ...
        'Callback', @branchUnselectAll ...
    );

    branchData = [num2cell(true(numel(branchNames), 1)), branchNames(:)];
    branchTable = uitable( ...
        'Parent', fig, ...
        'Data', branchData, ...
        'ColumnName', {'Export', 'Branch'}, ...
        'ColumnFormat', {'logical', 'char'}, ...
        'ColumnEditable', [true false], ...
        'ColumnWidth', {60 285}, ...
        'RowName', [], ...
        'Position', [20 95 350 285] ...
    );

    % Time point checklist, also preselected by default.
    uicontrol( ...
        'Parent', fig, ...
        'Style', 'text', ...
        'String', 'Time points:', ...
        'HorizontalAlignment', 'left', ...
        'Position', [390 385 100 22] ...
    );

    uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Select All', ...
        'Position', [590 385 60 22], ...
        'Callback', @timePointSelectAll ...
    );

    uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Unselect All', ...
        'Position', [655 385 65 22], ...
        'Callback', @timePointUnselectAll ...
    );

    timePointData = [num2cell(true(numel(timePointDisplay), 1)), timePointDisplay(:)];
    timePointTable = uitable( ...
        'Parent', fig, ...
        'Data', timePointData, ...
        'ColumnName', {'Export', 'Time point'}, ...
        'ColumnFormat', {'logical', 'char'}, ...
        'ColumnEditable', [true false], ...
        'ColumnWidth', {60 285}, ...
        'RowName', [], ...
        'Position', [390 95 350 285] ...
    );

    % Confirm returns the selections, cancel exits without applying them.
    uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Confirm', ...
        'Position', [490 35 110 38], ...
        'Callback', @onConfirm ...
    );

    uicontrol( ...
        'Parent', fig, ...
        'Style', 'pushbutton', ...
        'String', 'Cancel', ...
        'Position', [620 35 110 38], ...
        'Callback', @onCancel ...
    );

    % Block until the user confirms or cancels the dialog.
    uiwait(fig);

    function onBrowse(~, ~)
        % Start the folder picker from the current path if possible.
        currentPath = get(outputFolderEdit, 'String');
        if ~isfolder(currentPath)
            currentPath = pwd;
        end

        % MATLAB uses uigetdir for directory selection dialogs.
        selectedPath = uigetdir(currentPath, 'Select output folder');
        if ~isequal(selectedPath, 0)
            set(outputFolderEdit, 'String', char(selectedPath));
        end
    end

    function branchSelectAll(~, ~)
        % Set all branch checkboxes to true.
        branchData(:, 1) = {true};
        branchTable.Data = branchData;
    end

    function branchUnselectAll(~, ~)
        % Set all branch checkboxes to false.
        branchData(:, 1) = {false};
        branchTable.Data = branchData;
    end

    function timePointSelectAll(~, ~)
        % Set all time point checkboxes to true.
        timePointData(:, 1) = {true};
        timePointTable.Data = timePointData;
    end

    function timePointUnselectAll(~, ~)
        % Set all time point checkboxes to false.
        timePointData(:, 1) = {false};
        timePointTable.Data = timePointData;
    end

    function onConfirm(~, ~)
        % Read the current UI state into the function outputs.
        selectedOutputBaseFolder = strtrim(get(outputFolderEdit, 'String'));
        selectedOutputFolderName = strtrim(get(outputFolderNameEdit, 'String'));
        dumpDirectlyToSelectedOutputFolder = logical(get(dumpDirectlyCheckbox, 'Value'));

        if dumpDirectlyToSelectedOutputFolder
            outputFolder = selectedOutputBaseFolder;
        elseif isempty(selectedOutputFolderName)
            outputFolder = selectedOutputBaseFolder;
        else
            outputFolder = fullfile(selectedOutputBaseFolder, selectedOutputFolderName);
        end

        selectedFormat = outputFormats{get(outputFormatDropdown, 'Value')};
        centerMeshes = logical(get(centerMeshCheckbox, 'Value'));
        branchMask = cell2mat(branchTable.Data(:, 1));
        timePointMask = cell2mat(timePointTable.Data(:, 1));

        selectedBranchIndices = find(branchMask);
        selectedTimePointIndices = find(timePointMask);
        selectedBranches = branchNames(selectedBranchIndices);

        selectedTimePoints = reshape(numericTimePoints(selectedTimePointIndices), 1, []);

        isCancelled = false;
        closeDialog();
    end

    function onCancel(~, ~)
        % Leave the default outputs in place when the user cancels.
        isCancelled = true;
        closeDialog();
    end

    function closeDialog()
        % Resume execution and close the modal figure if it still exists.
        if isvalid(fig)
            uiresume(fig);
            delete(fig);
        end
    end
end