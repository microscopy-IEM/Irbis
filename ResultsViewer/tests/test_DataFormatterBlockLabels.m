classdef test_DataFormatterBlockLabels < matlab.unittest.TestCase
    methods (TestClassSetup)
        function setupOnce(~)
            addpath(fullfile(pwd, '..', '..'));
        end
    end



    methods (Test)
        function pivotedXYLabelsSurviveSummarizedCategoricalColorcoding(testCase)
            pivotedTable = array2table( ...
                [10 20; 30 40], ...
                'VariableNames', {'1', '2'}, ...
                'RowNames', {'A'; 'B'});
            pivotedTable.Properties.UserData.columnParameter = 'timePoint';
            pivotedTable.Properties.UserData.groupedDataParameter = 'Value';

            summarizedTable = table( ...
                categorical({'control'; 'treated'}), ...
                'VariableNames', {'Category'}, ...
                'RowNames', {'A'; 'B'});

            pivotedProcessor = LocalDataFormatterProcessor(pivotedTable, false);
            summarizedProcessor = LocalDataFormatterProcessor(summarizedTable, true);
            plotManager = LocalPlotManagerForDataFormatter();

            formatter = DataFormatter( ...
                plotManager, ...
                {pivotedProcessor, summarizedProcessor}, ...
                true, ...
                false, ...
                false, ...
                2, ...
                {'Pivoted', 'Summarized'});
            cleanup = onCleanup(@() delete(formatter));

            % The summarized table provides only categorical colorcoding. Its
            % label must become groupLabel, while the pivoted block keeps both of
            % its own internal labels for x/y.
            formatter.processData(summarizedProcessor);

            testCase.verifyEqual(plotManager.lastData.xLabel, 'timePoint');
            testCase.verifyEqual(plotManager.lastData.yLabel, 'Value');
            testCase.verifyEqual(plotManager.lastData.groupLabel, 'Category');
        end



        function numericExtraColumnBecomesScatterColorWhenNoCategoricalExists(testCase)
            sourceTable = table( ...
                [10; 20; 30], ...
                [1; 2; 3], ...
                [0.2; 0.5; 0.8], ...
                'VariableNames', {'Value', 'TimePoint', 'Intensity'}, ...
                'RowNames', {'cell_A'; 'cell_B'; 'cell_C'});

            processor = LocalDataFormatterProcessor(sourceTable, [false false false]);
            plotManager = LocalPlotManagerForDataFormatter();

            formatter = DataFormatter( ...
                plotManager, ...
                {processor}, ...
                true, ...
                false, ...
                false, ...
                2, ...
                {'Full'}, ...
                "two variables");
            cleanup = onCleanup(@() delete(formatter));

            % With no categorical column available, two-variable plots can use a numeric extra column as continuous point color.
            % The remaining columns are still selected in the existing x/y order.
            formatter.processData(processor);

            testCase.verifyEqual(plotManager.lastData.xLabel, 'TimePoint');
            testCase.verifyEqual(plotManager.lastData.yLabel, 'Value');
            testCase.verifyEqual(plotManager.lastData.colorLabel, 'Intensity');
            testCase.verifyEqual(plotManager.lastData.colorType, "numeric");
            testCase.verifyEqual(plotManager.lastData.colorScope, "point");
            testCase.verifyEmpty(plotManager.lastData.groupData);
            testCase.verifyEqual(plotManager.lastData.colorData, [0.2; 0.5; 0.8]);
            testCase.verifyEqual(plotManager.lastData.rowNames, ["cell_A"; "cell_B"; "cell_C"]);
        end



        function requiredCategoricalAxisIsNotStolenAsColor(testCase)
            sourceTable = table( ...
                categorical({'control'; 'treated'; 'control'}), ...
                [10; 20; 30], ...
                'VariableNames', {'Condition', 'Value'});

            processor = LocalDataFormatterProcessor(sourceTable, [true false]);
            plotManager = LocalPlotManagerForDataFormatter();

            formatter = DataFormatter( ...
                plotManager, ...
                {processor}, ...
                true, ...
                false, ...
                false, ...
                2, ...
                {'Full'}, ...
                "two variables");
            cleanup = onCleanup(@() delete(formatter));

            % A categorical column is only colorcoding if enough required plot data remains after removing it.
            % This keeps categorical x/y axes available for box plots when the user selected exactly two columns.
            formatter.processData(processor);

            testCase.verifyEqual(plotManager.lastData.xLabel, 'Value');
            testCase.verifyEqual(plotManager.lastData.yLabel, 'Condition');
            testCase.verifyEmpty(plotManager.lastData.groupData);
            testCase.verifyEqual(plotManager.lastData.colorType, "none");
        end
    end
end
